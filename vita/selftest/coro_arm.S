@ selftest/coro_arm.S - hand-written ARMv7-A coroutine switch + register-checking test body (T3).
@
@ Context layout (26 words = 104 bytes, 8-byte aligned):
@     [0..7]   r4..r11        [8] sp        [9] lr (resume address)        [10..25] d8..d15
@ AAPCS callee-saved state that is NOT saved here: FPSCR (the port never changes the rounding mode), r9 as a platform
@ register (Vita uses r9 as an ordinary callee-saved register in user code; UNVERIFIED but r9 is saved anyway).
@ Everything is assembled in ARM state (.arm); it is called from Thumb-2 C++ through BL/BLX veneers generated by the linker.
        .syntax unified
        .arch   armv7-a
        .fpu    neon
        .text
        .arm
        .align  4

@ void st_co_switch(uint32_t* from /*r0*/, const uint32_t* to /*r1*/);
        .global st_co_switch
        .type   st_co_switch, %function
st_co_switch:
        mov     r12, sp                         @ r12 (ip) is caller-saved scratch; STM/LDM store in ascending register order,
        stmia   r0!, {r4-r11, r12, lr}          @ so the layout is exactly [r4..r11][sp][lr]
        vstmia  r0!, {d8-d15}
        ldmia   r1!, {r4-r11, r12, lr}
        vldmia  r1!, {d8-d15}
        mov     sp, r12
        bx      lr
        .size   st_co_switch, .-st_co_switch

@ First resume of a coroutine lands here with r4 = argument, r5 = entry function (ARM or Thumb, interworking BX).
        .global st_co_tramp
        .type   st_co_tramp, %function
st_co_tramp:
        mov     r0, r4
        bx      r5
        udf     #0
        .size   st_co_tramp, .-st_co_tramp

@ Test body. r0 = B*, struct B (uint32_t words):
@   [0] self_ctx  [1] next_ctx  [2] sched_ctx  [3] id  [4] seed  [5] errors  [6] runs  [7] counter_ptr
@ Loop: fill r4-r11 and d8-d15 with values derived from (seed, id), switch to next (or to the scheduler when the shared
@ counter reaches zero), then on resume verify that all of r4-r11 and d8-d15 still hold what we put there.
        .macro  CHK reg, imm
        eor     r12, r3, #\imm
        cmp     \reg, r12
        addne   r1, r1, #1
        .endm

        .global st_co_body
        .type   st_co_body, %function
st_co_body:
        sub     sp, sp, #16
        str     r0, [sp]
1:      @ ---- fill
        ldr     r0, [sp]
        ldr     r2, [r0, #16]
        add     r2, r2, #1
        str     r2, [r0, #16]
        ldr     r1, [r0, #12]
        eor     r3, r2, r1, lsl #24
        eor     r4,  r3, #0x11
        eor     r5,  r3, #0x22
        eor     r6,  r3, #0x33
        eor     r7,  r3, #0x44
        eor     r8,  r3, #0x55
        eor     r9,  r3, #0x66
        eor     r10, r3, #0x77
        eor     r11, r3, #0x88
        vmov    d8,  r4,  r5
        vmov    d9,  r6,  r7
        vmov    d10, r8,  r9
        vmov    d11, r10, r11
        vmov    d12, r4,  r11
        vmov    d13, r5,  r10
        vmov    d14, r6,  r9
        vmov    d15, r7,  r8
        @ ---- pick the target and switch
        ldr     r0, [sp]
        ldr     r2, [r0, #28]
        ldr     r3, [r2]
        subs    r3, r3, #1
        str     r3, [r2]
        ldreq   r1, [r0, #8]
        ldrne   r1, [r0, #4]
        ldr     r0, [r0, #0]
        bl      st_co_switch
        @ ---- verify after resume
        ldr     r0, [sp]
        ldr     r2, [r0, #16]
        ldr     r1, [r0, #12]
        eor     r3, r2, r1, lsl #24
        mov     r1, #0
        CHK     r4,  0x11
        CHK     r5,  0x22
        CHK     r6,  0x33
        CHK     r7,  0x44
        CHK     r8,  0x55
        CHK     r9,  0x66
        CHK     r10, 0x77
        CHK     r11, 0x88
        vmov    r0, r2, d8
        CHK     r0, 0x11
        CHK     r2, 0x22
        vmov    r0, r2, d9
        CHK     r0, 0x33
        CHK     r2, 0x44
        vmov    r0, r2, d10
        CHK     r0, 0x55
        CHK     r2, 0x66
        vmov    r0, r2, d11
        CHK     r0, 0x77
        CHK     r2, 0x88
        vmov    r0, r2, d12
        CHK     r0, 0x11
        CHK     r2, 0x88
        vmov    r0, r2, d13
        CHK     r0, 0x22
        CHK     r2, 0x77
        vmov    r0, r2, d14
        CHK     r0, 0x33
        CHK     r2, 0x66
        vmov    r0, r2, d15
        CHK     r0, 0x44
        CHK     r2, 0x55
        ldr     r0, [sp]
        ldr     r2, [r0, #20]
        add     r2, r2, r1
        str     r2, [r0, #20]
        ldr     r2, [r0, #24]
        add     r2, r2, #1
        str     r2, [r0, #24]
        b       1b
        .size   st_co_body, .-st_co_body

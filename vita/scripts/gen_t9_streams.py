#!/usr/bin/env python3
"""Generates selftest/t9_streams.h: a tiny synthetic H.264 test stream (testsrc2 + noise, 480x272, 12 frames, Constrained
Baseline, no B-frames) and the CRC32 of each decoded YUV420p frame as produced by a reference decoder.
No game data is involved. Needs /usr/bin/ffmpeg (6.x with libx264) and ffprobe. Output is checked in (it is ~22 KB of bytes)."""
import subprocess, zlib, os, sys, tempfile
W, H, N = 480, 272, 12
ff = "/usr/bin/ffmpeg"
with tempfile.TemporaryDirectory() as d:
    h264 = os.path.join(d, "t9.h264")
    yuv = os.path.join(d, "t9.yuv")
    subprocess.check_call([ff, "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i",
        "testsrc2=size=%dx%d:rate=30:duration=0.5,noise=alls=14:allf=t+u:all_seed=7" % (W, H), "-frames:v", str(N),
        "-c:v", "libx264", "-profile:v", "baseline", "-level", "3.0", "-preset", "medium", "-crf", "27", "-g", str(N), "-bf", "0", "-refs", "1",
        "-x264-params", "ref=1:bframes=0:cabac=0:weightp=0:8x8dct=0:threads=1:sliced-threads=0:scenecut=0", "-pix_fmt", "yuv420p", "-f", "h264", h264])
    subprocess.check_call([ff, "-hide_banner", "-loglevel", "error", "-y", "-threads", "1", "-i", h264, "-f", "rawvideo", "-pix_fmt", "yuv420p", yuv])
    es = open(h264, "rb").read()
    raw = open(yuv, "rb").read()
fs = W * H * 3 // 2
assert len(raw) == fs * N, (len(raw), fs * N)
crcs = [zlib.crc32(raw[i * fs:(i + 1) * fs]) & 0xFFFFFFFF for i in range(N)]
out = []
out.append("// GENERATED by scripts/gen_t9_streams.py - synthetic H.264 test pattern, not game data. Do not edit.")
out.append("#pragma once")
out.append("#include <stdint.h>")
out.append("#include <stddef.h>")
out.append("static const int kT9Width = %d, kT9Height = %d, kT9Frames = %d;" % (W, H, N))
out.append("static const uint32_t kT9FrameCrc[%d] = {%s};" % (N, ", ".join("0x%08X" % c for c in crcs)))
out.append("static const size_t kT9H264Size = %d;" % len(es))
out.append("static const uint8_t kT9H264[%d] = {" % len(es))
for i in range(0, len(es), 24):
    out.append("  " + ", ".join("0x%02X" % b for b in es[i:i + 24]) + ",")
out.append("};")
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "selftest", "t9_streams.h")
open(path, "w").write("\n".join(out) + "\n")
print("wrote", os.path.normpath(path), len(es), "bytes of H.264,", N, "frames")
